// Resolves the Iconsax icons this app uses against the INSTALLED iconsax-react
// package and writes components/ui/icons.generated.js with named imports only for
// icons that really exist. Each alias in lib/icon-map.json lists candidate names;
// the first one that exists wins. Missing icons degrade to a neutral glyph
// instead of breaking the build, and the bundle stays tree-shaken.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mapFile = path.join(root, 'lib/icon-map.json');
const outFile = path.join(root, 'components/ui/icons.generated.js');
const map = JSON.parse(readFileSync(mapFile, 'utf8'));

async function loadExports() {
  try {
    const mod = await import('iconsax-react');
    const names = new Set(Object.keys(mod));
    if (mod.default && typeof mod.default === 'object') Object.keys(mod.default).forEach((k) => names.add(k));
    if (names.size > 20) return names;
  } catch { /* fall through */ }
  try {
    const require = createRequire(path.join(root, 'package.json'));
    const names = new Set(Object.keys(require('iconsax-react')));
    if (names.size > 20) return names;
  } catch { /* not installed */ }
  return null;
}

const available = await loadExports();
if (!available) console.warn('[icons] iconsax-react not found - using first-choice names. Run `npm install`.');

const picked = {};
const missing = [];
for (const [alias, candidates] of Object.entries(map)) {
  const hit = available ? candidates.find((n) => available.has(n)) : candidates[0];
  if (hit) picked[alias] = hit; else missing.push(alias);
}

const names = [...new Set(Object.values(picked))].sort();
const lines = Object.entries(picked).map(([a, n]) => `  ${JSON.stringify(a)}: ${n},`);
const body =
  `// AUTO-GENERATED by scripts/gen-icons.mjs (runs before dev/build). Do not edit.\n` +
  `import { ${names.join(', ')} } from 'iconsax-react';\n\n` +
  `export const ICONS = {\n${lines.join('\n')}\n};\n`;

if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== body) writeFileSync(outFile, body);
if (missing.length) console.warn(`[icons] No Iconsax match for: ${missing.join(', ')} (fallback glyph will be used)`);
else console.log(`[icons] ${Object.keys(picked).length} icons resolved.`);
